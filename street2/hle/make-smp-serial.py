"""Street 2: project/src/hle_smp_serial.c from hle/smp_serial_functions.json
(street1's EA heap / MemoryX / stream functions mapped by tools/addrmap.py).
Functions without a generated definition are dropped from the table."""
from pathlib import Path
import json, re

here = Path(__file__).resolve().parent
gen = here.parent / 'project/src/recomp/gen'
table = json.loads((here / 'smp_serial_functions.json').read_text(encoding='utf-8'))
defined = set()
for f in gen.glob('recomp_00*.c'):
    for m in re.finditer(r'^void sub_([0-9A-F]{8})(?:_gen)?\(void\)', f.read_text(encoding='utf-8', errors='replace'), re.M):
        defined.add(m.group(1))
drop = [k for k in table if k not in defined]
for k in drop:
    del table[k]
(here / 'smp_serial_functions.json').write_text(json.dumps(table, indent=1) + '\n', encoding='utf-8')
addrs = sorted(int(k, 16) for k in table)
out = ['/*', ' * Generated by street2/hle/make-smp-serial.py (see street1 for the rationale):',
       ' * title heap and stream code runs under the guest kernel lock with RECOMP_GUEST_SMP.',
       ' * Without SMP guest_cpu_native_enter() is a no-op.', ' */',
       '#include "recomp/gen/recomp_types.h"', '',
       'int guest_cpu_native_enter(void);', 'void guest_cpu_native_leave(int token);', '']
out += [f'void sub_{a:08X}_gen(void);' for a in addrs] + ['']
out += [f'void sub_{a:08X}(void) {{ int s = guest_cpu_native_enter(); sub_{a:08X}_gen(); guest_cpu_native_leave(s); }}' for a in addrs]
(here.parent / 'project/src/hle_smp_serial.c').write_text('\n'.join(out) + '\n', encoding='utf-8', newline='\n')
print(len(addrs), 'serial functions', len(drop), 'dropped')
